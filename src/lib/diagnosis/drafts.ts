import "server-only";

// 액션 플랜의 실행 초안 (D-23): 할 일 카드마다 바로 쓸 수 있는 글 · 문구 · 메일 초안.
// ★ 실제 연결 지점: Anthropic 키가 생기면 Claude 가 브랜드 · 진단 원문을 보고 초안을 쓴다.
//   지금은 기본 틀 — 【】 칸은 오너가 채운다. 없는 사실(수치 · 후기)은 넣지 않는다.

type DraftInput = {
  cardType: string;
  title: string;
  brandName: string;
  category: string;
  topQuestion: string | null; // 가장 가까운 기회 질문
  sourceExamples: string[];
};

export function makeDraft(d: DraftInput): string {
  const q = d.topQuestion ?? `${d.category} 추천해 줘`;
  switch (d.cardType) {
    case "faq_content":
      return [
        `[블로그 · FAQ 글 초안]`,
        `제목: ${q.replace(/해 줘$|알려 줘$/, "")} — ${d.brandName} 이 답해요`,
        ``,
        `1. 한 줄 답: ${d.brandName} 의 【대표 제품명】은 【누구에게 · 어떤 상황에】 잘 맞아요.`,
        `2. 이런 분께 추천해요: 【대상 1】, 【대상 2】`,
        `3. 한눈에 보기 (표)`,
        `   | 제품 | 가격 | 용량 | 특징 |`,
        `   | 【제품명】 | 【가격】 | 【용량】 | 【향 · 성분 등 특징】 |`,
        `4. 고르는 기준: 【상황】이라면 【이유】 때문에 【제품】을 권해요.`,
        `5. 자주 묻는 질문: 【질문 · 답 2~3개】`,
        ``,
        `※ 질문 문장을 제목과 첫 문단에 그대로 넣으면 AI 가 답을 찾기 쉬워요.`,
      ].join("\n");
    case "site_info":
      return [
        `[상세페이지 정보 보강 초안]`,
        `· 한 줄 소개: ${d.brandName} 【대표 제품명】 — 【핵심 특징 한 문장】`,
        `· 이런 분께: 【대상 · 상황 2~3개】`,
        `· 핵심 정보 (표로): 가격 【】 / 용량 【】 / 주요 성분 · 향 노트 【】 / 지속 시간 · 사용 기간 【】`,
        `· 쓰는 법: 【1 · 2 · 3 단계】`,
        `· 선물 · 쓰는 상황: 【집들이 · 생일 · 셀프 선물 등】`,
        `· 자주 묻는 질문 3개: 【질문 · 답】`,
        ``,
        `※ AI 는 숫자 · 표 · 질문형 문단을 잘 인용해요. "좋은 향" 같은 말보다 구체 정보를 적어 주세요.`,
      ].join("\n");
    case "external_mention":
      return [
        `[블로그 · 매거진 소개 제안 메일 초안]`,
        `제목: [${d.brandName}] ${d.category} 소개 자료를 보내 드려요`,
        ``,
        `안녕하세요, ${d.brandName} 【이름】입니다.`,
        `【매체명】에서 "${q}" 관련 글을 인상 깊게 봤어요.`,
        `저희는 【한 줄 브랜드 소개】를 만드는 브랜드예요.`,
        `- 대표 제품: 【제품명 · 가격 · 특징】`,
        `- 함께 드릴 수 있는 것: 【제품 샘플 · 이미지 · 소개 자료】`,
        `다음 추천 글을 쓰실 때 참고해 주시면 감사하겠어요.`,
        ``,
        d.sourceExamples.length ? `※ 이번 진단에서 자주 인용된 곳: ${d.sourceExamples.join(", ")}` : `※ 카테고리 추천 글을 쓰는 블로그 · 매거진부터 찾아 보세요.`,
      ].join("\n");
    case "review_community":
      return [
        `[후기 요청 메시지 초안]`,
        `안녕하세요, ${d.brandName} 입니다. 【제품명】 써 보신 느낌이 궁금해요.`,
        `【커뮤니티 이름】에 솔직한 후기를 남겨 주시면 【감사 표시 — 할인 쿠폰 등, 커뮤니티 규칙 확인】를 드릴게요.`,
        `- 좋았던 점 · 아쉬운 점 모두 괜찮아요`,
        `- "${q}" 처럼 어떤 상황에 썼는지 적어 주시면 다른 분들께 도움이 돼요`,
        ``,
        `※ 커뮤니티마다 광고 · 협찬 규칙이 달라요. 협찬이면 반드시 표시해 주세요.`,
      ].join("\n");
    case "shopping_listing":
      return [
        `[쇼핑 검색 상품 등록 체크리스트]`,
        `□ 상품명: ${d.brandName} 【제품명】 【용량】 【특징 키워드】`,
        `□ 가격 · 할인 정보 정확히`,
        `□ 카테고리: ${d.category} 세부 분류까지`,
        `□ 상세 정보: 성분 · 향 노트 · 용량 · 사용 기간`,
        `□ 대표 이미지 · 사용 장면 이미지`,
        `□ 구매 후기 노출 설정`,
        d.sourceExamples.length ? `※ 이번 진단에서 인용된 쇼핑 출처: ${d.sourceExamples.join(", ")}` : ``,
      ].filter(Boolean).join("\n");
    case "press_release":
      return [
        `[보도자료 초안]`,
        `제목: ${d.brandName}, 【소식 한 줄 — 신제품 출시 · 런칭 · 협업 등】`,
        ``,
        `【날짜】 — ${d.category} 브랜드 ${d.brandName} 이 【소식】을 발표했다.`,
        `【제품 · 소식 설명 2~3문장 — 가격 · 특징 · 출시처】`,
        `${d.brandName} 【대표 이름 · 직함】은 "【한 줄 인터뷰】"라고 말했다.`,
        `문의: 【연락처】`,
      ].join("\n");
    default:
      return `[실행 초안]\n${d.title}\n【할 일을 구체적으로 적어 주세요】`;
  }
}
